-- Comores Express : schéma Supabase (à exécuter dans SQL Editor). Sécurité par RLS.
create extension if not exists pgcrypto;

create table public.profiles (
  id uuid primary key references auth.users on delete cascade,
  nom text, telephone text, vehicule text, plaque text, note numeric default 5,
  role text not null default 'passager' check (role in ('passager','chauffeur','admin')),
  created_at timestamptz default now()
);
create function public.mon_role() returns text language sql stable security definer set search_path = public
as $$ select role from public.profiles where id = auth.uid() $$;

create function public.nouveau_profil() returns trigger language plpgsql security definer set search_path = public
as $$ begin insert into public.profiles(id) values (new.id) on conflict do nothing; return new; end $$;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.nouveau_profil();

create table public.trajets (
  id bigint generated by default as identity primary key,
  chauffeur_id uuid not null references public.profiles(id),
  depart text not null, arrivee text not null, heure text not null,
  categorie text not null check (categorie in ('taxi','minibus','bus','vedette')),
  distance_km numeric, duree text, prix int not null check (prix >= 0),
  statut text not null default 'Programmé', retard_minutes int not null default 0, motif_retard text not null default '',
  created_at timestamptz default now()
);
alter table public.trajets replica identity full;

create table public.billets (
  id text primary key default 'TICKET-' || upper(substr(replace(gen_random_uuid()::text,'-',''),1,8)),
  trajet_id bigint not null references public.trajets(id),
  user_id uuid not null default auth.uid() references public.profiles(id),
  date_depart date not null, siege int not null check (siege > 0),
  prix int not null, paiement text, statut text, telephone text, reference text,
  bagage boolean default false, escale text, promo text, chauffeur_tel text,
  annule boolean not null default false, created_at timestamptz default now()
);
create unique index billets_siege_unique on public.billets(trajet_id, date_depart, siege) where not annule;

create table public.positions (
  trajet_id bigint primary key references public.trajets(id) on delete cascade,
  lat double precision not null, lng double precision not null, vitesse real, updated_at timestamptz default now()
);

-- Vues publiques SANS téléphone du chauffeur ni données personnelles
create view public.trajets_publics as
  select t.*, p.nom as chauffeur_nom, p.vehicule, p.plaque, p.note
  from public.trajets t join public.profiles p on p.id = t.chauffeur_id;
create view public.sieges_occupes as
  select trajet_id, date_depart, siege from public.billets where not annule;
grant select on public.trajets_publics, public.sieges_occupes to anon, authenticated;

alter table public.profiles enable row level security;
alter table public.trajets  enable row level security;
alter table public.billets  enable row level security;
alter table public.positions enable row level security;

-- profiles : chacun lit/modifie le sien ; le rôle ne peut PAS être changé par l'utilisateur
create policy p_sel on public.profiles for select using (id = auth.uid());
create policy p_upd on public.profiles for update using (id = auth.uid())
  with check (id = auth.uid() and role = public.mon_role());
-- trajets : lecture publique ; écriture réservée aux chauffeurs validés, sur leurs trajets
create policy t_sel on public.trajets for select using (true);
create policy t_ins on public.trajets for insert with check (chauffeur_id = auth.uid() and public.mon_role() in ('chauffeur','admin'));
create policy t_upd on public.trajets for update using (chauffeur_id = auth.uid()) with check (chauffeur_id = auth.uid());
create policy t_del on public.trajets for delete using (chauffeur_id = auth.uid());
-- billets : lecture du passager ou du chauffeur du trajet ; AUCUNE écriture directe (passe par les fonctions)
create policy b_sel on public.billets for select using (
  user_id = auth.uid() or exists (select 1 from public.trajets t where t.id = trajet_id and t.chauffeur_id = auth.uid()));
-- positions : le chauffeur écrit ; seuls lui et les passagers ayant un billet du jour lisent
create policy g_ins on public.positions for insert with check (exists (select 1 from public.trajets t where t.id = trajet_id and t.chauffeur_id = auth.uid()));
create policy g_upd on public.positions for update using (exists (select 1 from public.trajets t where t.id = trajet_id and t.chauffeur_id = auth.uid()));
create policy g_sel on public.positions for select using (
  exists (select 1 from public.trajets t where t.id = trajet_id and t.chauffeur_id = auth.uid())
  or exists (select 1 from public.billets b where b.trajet_id = positions.trajet_id and b.user_id = auth.uid() and not b.annule and b.date_depart = current_date));

-- Réservation atomique multi-sièges (prix recalculé côté serveur)
create function public.reserver_places(
  p_trajet bigint, p_date date, p_sieges int[], p_mode text, p_provider text,
  p_telephone text, p_reference text, p_bagage boolean, p_escale text, p_promo text
) returns setof public.billets language plpgsql security definer set search_path = public as $$
declare t public.trajets; maxp int; s int; unit int; tel text; st text; b public.billets;
begin
  if auth.uid() is null then raise exception 'Connexion requise'; end if;
  select * into t from public.trajets where id = p_trajet;
  if not found then raise exception 'Trajet introuvable'; end if;
  if t.statut in ('Annulé','Terminé') then raise exception 'Trajet non réservable'; end if;
  if p_date < current_date or p_date > current_date + 60 then raise exception 'Date invalide'; end if;
  if coalesce(array_length(p_sieges,1),0) not between 1 and 6 then raise exception '1 à 6 sièges par réservation'; end if;
  maxp := case t.categorie when 'taxi' then 4 when 'minibus' then 15 when 'bus' then 30 else 20 end;
  unit := t.prix + case when p_bagage then 500 else 0 end;
  unit := case upper(coalesce(p_promo,''))
            when 'BIENVENUE' then unit - round(unit*0.10)::int
            when 'COMORES'   then greatest(unit - 200, 0) else unit end;
  if p_mode = 'maintenant' then
    if p_telephone !~ '^[0-9]{7}$' or coalesce(p_reference,'') = '' then raise exception 'Téléphone/référence Mobile Money invalides'; end if;
    st := 'Paiement en vérification';   -- confirmé uniquement par le webhook du prestataire
  else st := 'Paiement en attente à bord'; end if;
  select telephone into tel from public.profiles where id = t.chauffeur_id;
  foreach s in array p_sieges loop
    if s < 1 or s > maxp then raise exception 'Siège % invalide', s; end if;
    begin
      insert into public.billets(trajet_id,date_depart,siege,prix,paiement,statut,telephone,reference,bagage,escale,promo,chauffeur_tel)
      values (p_trajet,p_date,s,unit,case when p_mode='maintenant' then p_provider else 'Espèces' end,st,p_telephone,p_reference,coalesce(p_bagage,false),p_escale,p_promo,tel)
      returning * into b;
    exception when unique_violation then raise exception 'Siège S% déjà occupé', s; end;
    return next b;
  end loop;
end $$;

create function public.annuler_billet(p_id text) returns void language sql security definer set search_path = public
as $$ update public.billets set annule = true, statut = 'Annulé' where id = p_id and user_id = auth.uid() and not annule $$;

revoke all on function public.reserver_places, public.annuler_billet from public, anon;
grant execute on function public.reserver_places, public.annuler_billet to authenticated;

alter publication supabase_realtime add table public.trajets, public.positions;

